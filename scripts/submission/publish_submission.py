"""Commit a validated submission to its own branch, open a PR to dev, and comment on the issue.

Runs in the publish job, after build_submission.py. It reads only report.json
and the files that script produced; it never runs anything from the submission.

    python publish_submission.py --report out/report.json --files out/files --site site
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

BASE_BRANCH = "dev"
MARKER = "<!-- poster-submission-bot -->"
STUDENT_DIR = re.compile(r"^20\d\d/Q[1-4]/Group [1-9]\d{0,3}/students/[^/\\]+$")


def run(*cmd, cwd=None, check=True):
    return subprocess.run(cmd, cwd=cwd, check=check, capture_output=True, text=True).stdout.strip()


def git_has(site, path):
    return subprocess.run(
        ["git", "cat-file", "-e", f"HEAD:{path}"], cwd=site, capture_output=True
    ).returncode == 0


def commit_and_open_pr(report, files, site):
    student_dir = report["student_dir"]
    group_dir = report["group_dir"]
    if not STUDENT_DIR.fullmatch(student_dir) or not student_dir.startswith(group_dir + "/"):
        raise ValueError(f"unexpected folder in report: {student_dir!r}")

    notes = []
    posters = Path(site) / "content" / "posters"
    dest = posters / student_dir
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(Path(files) / student_dir, dest)

    group_info = f"content/posters/{group_dir}/group_info.yaml"
    if git_has(site, group_info):
        theirs = run("git", "show", f"HEAD:{group_info}", cwd=site)
        ours = (Path(files) / group_dir / "group_info.yaml").read_text(encoding="utf-8").strip()
        if theirs != ours:
            notes.append(
                "Your group already has project details on the website, so the project title and "
                "supervisors from this form were not used. Ask the course staff if they need changing."
            )
    else:
        shutil.copy(Path(files) / group_dir / "group_info.yaml", posters / group_dir / "group_info.yaml")

    branch = f"poster-submission/issue-{report['issue']}"
    title = f"Add Group {report['group']} files ({report['student']})"
    run("git", "checkout", "-B", branch, cwd=site)
    run("git", "add", "--sparse", f"content/posters/{group_dir}", cwd=site)
    run("git", "commit", "--allow-empty", "-m", title, "-m", f"From #{report['issue']}.", cwd=site)
    run("git", "push", "--force", "origin", branch, cwd=site)

    existing = json.loads(run(
        "gh", "pr", "list", "--head", branch, "--state", "open", "--json", "url", cwd=site
    ))
    if existing:
        return existing[0]["url"], notes
    body = (
        f"Submitted through #{report['issue']}. Files are generated by the poster-submission "
        f"workflow; edit the issue to change them.\n\nPreview image: {report['preview_kb']} kB."
    )
    url = run(
        "gh", "pr", "create", "--base", BASE_BRANCH, "--head", branch,
        "--title", title, "--body", body, cwd=site,
    )
    return url, notes


def comment_body(report, pr_url=None, notes=()):
    lines = [MARKER]
    if report["ok"]:
        lines.append(f"Thanks, {report['student']}. Your submission passed the checks.")
        if pr_url:
            lines.append(f"\nThe course staff will review it in {pr_url}. Edit this issue to change anything.")
    else:
        lines.append("Your submission cannot be added yet. Please fix the following and edit this issue:\n")
        lines += [f"- {e}" for e in report["errors"]]
    extra = list(report.get("warnings", [])) + list(notes)
    if extra:
        lines.append("\nNotes:\n")
        lines += [f"- {w}" for w in extra]
    return "\n".join(lines)


def upsert_comment(issue, body):
    """Keep one bot comment per issue, updated on every run."""
    repo = os.environ["GITHUB_REPOSITORY"]
    mine = run(
        "gh", "api", "--paginate", f"repos/{repo}/issues/{issue}/comments",
        "--jq", f'.[] | select(.body | startswith("{MARKER}")) | .id',
    ).split()
    if mine:
        run("gh", "api", "-X", "PATCH", f"repos/{repo}/issues/comments/{mine[-1]}", "-f", f"body={body}")
    else:
        run("gh", "api", f"repos/{repo}/issues/{issue}/comments", "-f", f"body={body}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--files", type=Path, required=True)
    parser.add_argument("--site", type=Path, required=True)
    args = parser.parse_args()

    report = json.loads(args.report.read_text(encoding="utf-8"))
    pr_url, notes = None, []
    if report["ok"]:
        pr_url, notes = commit_and_open_pr(report, args.files, args.site)
    upsert_comment(report["issue"], comment_body(report, pr_url, notes))
    label = "needs-changes"
    action = "--remove-label" if report["ok"] else "--add-label"
    run("gh", "issue", "edit", str(report["issue"]), action, label, check=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
